CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(20) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE teams (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  captain_name VARCHAR(100) NOT NULL,
  captain_email VARCHAR(255) NOT NULL,
  user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE team_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL REFERENCES teams(id),
  name VARCHAR(100) NOT NULL
);
CREATE INDEX idx_team_members_team ON team_members(team_id);

CREATE TABLE questions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_number INTEGER NOT NULL UNIQUE,
  clue VARCHAR(500) NOT NULL,
  answer VARCHAR(100) NOT NULL,
  direction VARCHAR(10) NOT NULL
);

CREATE TABLE round1_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL UNIQUE REFERENCES teams(id),
  status VARCHAR(20) NOT NULL,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  completed_at TIMESTAMP WITH TIME ZONE,
  correct_count INTEGER NOT NULL DEFAULT 0,
  incorrect_count INTEGER NOT NULL DEFAULT 0,
  skipped_count INTEGER NOT NULL DEFAULT 0,
  timeout_count INTEGER NOT NULL DEFAULT 0,
  score INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE round1_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES round1_sessions(id),
  question_id BIGINT NOT NULL REFERENCES questions(id),
  status VARCHAR(20) NOT NULL,
  started_at TIMESTAMP WITH TIME ZONE NOT NULL,
  expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
  closed_at TIMESTAMP WITH TIME ZONE,
  submitted_answer VARCHAR(100),
  CONSTRAINT uq_attempt_session_question UNIQUE (session_id, question_id)
);
CREATE INDEX idx_attempts_session ON round1_attempts(session_id);

CREATE TABLE qualifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL UNIQUE REFERENCES teams(id),
  status VARCHAR(20) NOT NULL,
  rank_no INTEGER,
  score INTEGER NOT NULL,
  decided_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE round2_challenges (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(200) NOT NULL,
  description VARCHAR(4000) NOT NULL,
  requirements VARCHAR(4000) NOT NULL,
  time_limit_minutes INTEGER NOT NULL,
  active BOOLEAN NOT NULL
);

CREATE TABLE round2_submissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL UNIQUE REFERENCES teams(id),
  challenge_id BIGINT NOT NULL REFERENCES round2_challenges(id),
  website_url VARCHAR(500) NOT NULL,
  github_url VARCHAR(500) NOT NULL,
  description VARCHAR(2000) NOT NULL,
  submitted_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE round2_evaluations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id BIGINT NOT NULL UNIQUE REFERENCES round2_submissions(id),
  status VARCHAR(20) NOT NULL,
  requirement_score INTEGER,
  functionality_score INTEGER,
  ui_score INTEGER,
  responsiveness_score INTEGER,
  technical_score INTEGER,
  accuracy_score INTEGER,
  final_score DOUBLE PRECISION,
  feedback VARCHAR(4000),
  error_message VARCHAR(1000),
  evaluated_at TIMESTAMP WITH TIME ZONE
);
