-- ============ Round 1: admin-managed crossword + per-team queue ============
CREATE TABLE round1_config (
  id BIGINT PRIMARY KEY,
  published BOOLEAN NOT NULL,
  grid_rows INTEGER NOT NULL,
  grid_cols INTEGER NOT NULL,
  published_at TIMESTAMP WITH TIME ZONE
);
INSERT INTO round1_config (id, published, grid_rows, grid_cols) VALUES (1, FALSE, 0, 0);

ALTER TABLE questions ADD COLUMN grid_row INTEGER;
ALTER TABLE questions ADD COLUMN grid_col INTEGER;
ALTER TABLE questions ADD COLUMN display_number INTEGER;

-- A question can now be attempted many times (wrong answer / timeout sends it to the end of the queue).
ALTER TABLE round1_attempts DROP CONSTRAINT uq_attempt_session_question;

CREATE TABLE round1_queue_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT NOT NULL REFERENCES round1_sessions(id),
  question_id BIGINT NOT NULL REFERENCES questions(id),
  sort_pos INTEGER NOT NULL,
  completed BOOLEAN NOT NULL,
  CONSTRAINT uq_queue_session_question UNIQUE (session_id, question_id)
);
CREATE INDEX idx_queue_session ON round1_queue_items(session_id);

CREATE TABLE team_sequence_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL REFERENCES teams(id),
  question_id BIGINT NOT NULL REFERENCES questions(id),
  sort_pos INTEGER NOT NULL,
  CONSTRAINT uq_sequence_team_question UNIQUE (team_id, question_id)
);

-- ============ Round 2: reference image, hidden evaluation prompt, AI builder ============
ALTER TABLE round2_challenges ADD COLUMN evaluation_prompt VARCHAR(8000);
ALTER TABLE round2_challenges ADD COLUMN published BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE round2_challenges SET evaluation_prompt =
 'Compare the participant website code with the reference screenshot. Judge how closely the page recreates the reference: layout and structure, spacing, colors, typography, components, images or placeholders, buttons, and responsive behavior. Reward faithful, working, clean results and penalize missing sections or invented content.'
 WHERE evaluation_prompt IS NULL;

CREATE TABLE round2_reference_images (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  challenge_id BIGINT NOT NULL UNIQUE REFERENCES round2_challenges(id),
  filename VARCHAR(120) NOT NULL,
  content_type VARCHAR(50) NOT NULL,
  data BYTEA NOT NULL,
  uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE round2_drafts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  team_id BIGINT NOT NULL UNIQUE REFERENCES teams(id),
  html VARCHAR(400000),
  generation_count INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

ALTER TABLE round2_submissions ADD COLUMN generated_html VARCHAR(400000);
ALTER TABLE round2_submissions ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'SUBMITTED';
ALTER TABLE round2_submissions ALTER COLUMN website_url DROP NOT NULL;
ALTER TABLE round2_submissions ALTER COLUMN github_url DROP NOT NULL;
ALTER TABLE round2_submissions ALTER COLUMN description DROP NOT NULL;

ALTER TABLE round2_evaluations ADD COLUMN raw_response VARCHAR(8000);

-- Under the new rule a session is COMPLETED only when every question was answered correctly.
-- Re-open older sessions that were marked completed under the previous "all attempted" rule.
UPDATE round1_sessions SET status = 'IN_PROGRESS', completed_at = NULL
 WHERE status = 'COMPLETED' AND correct_count < (SELECT COUNT(*) FROM questions);
